/**
 * الرئيسية — «مركز القيادة» (أمر المالك ٢٠٢٦/١٠/١٣).
 *
 * مُودَع كمساعد غير مسار (بادئة الشرطة) ليقتطعه الموجّه من حزمة الدخول:
 * ميزانية الأداء تحت السقف بهامش ضيّق، فسطحٌ جديد لا يُحمَّل إلا عند زيارته.
 * والمسارَان `/` و`/blueprint` يصيّران هذه الصفحة نفسها — تسجيلان لصفحةٍ واحدة.
 *
 * ## الأمر والمواصفة
 *
 * «طبّق هذا الشكل بالتمام والكمال» — صورة مركز القيادة
 * (`docs/design/reference/home-command-center-mockup-2026-10-13.jpg`)، والمواصفة
 * الهندسية `docs/design/10-home-command-center-prompt.md`. قراراتها السبعة (§2)
 * ملزِمة، وهي **آخر نصٍّ صريح للمالك على الرئيسية** (المادة ٣٥)، فنسخت:
 *   • العنوان البطل المرئي — باقٍ `<h1>` مخفيًّا بصريًّا يحمل اسم المنتج؛
 *   • الصدر الثلاثي (بطاقات المناطق · منصّة سَدِيد · «توصيات سَدِيد»)؛
 *   • بطاقة المخاطر الواحدة (V5) — تحلّ محلّها قائمة «أبرز المخاطر»؛
 *   • شريط «سجل القرارات» — ليس في الصورة؛
 *   • موضع مبدّل الوضع — من الشريط العلوي إلى صفّ الترويسة، مبدّلٌ واحد.
 * وما عدا ذلك باقٍ: كل قاعدة دستورية في §3.
 *
 * ## الترتيب يسارًا ← يمينًا، والنصّ عربيّ (قرار المالك D5)
 *
 * «كما في الصورة حرفيًّا»: الشريط الجانبي **يسارًا**، والخريطة وسطًا يسارًا،
 * وبطاقة سَدِيد يمينًا، وصفّ المؤشرات يبدأ من اليسار. فالحاويات هنا ترتيبٌ
 * فقط تحت `dir="ltr"`، **وكل بطاقة وورقة تعلن اتجاه لغتها** (`dir="rtl"`):
 * لا يُقلب نصٌّ عربيّ لينقلب الترتيب. والتنقّل بلوحة المفاتيح يتبع الترتيب
 * المرئي نفسه لأن ترتيب DOM هو ترتيب الرسم.
 *
 * ## القشرة ليست هنا (أمر المالك ٢٠٢٦/١٠/١٨)
 *
 * «اجعل جميع صفحات النظام بنفس تخطيط وهيئة الصفحة الرئيسية» — فالشريط
 * والترويسة ولوحة الأوامر والخلفية (`HoloVideoEngine` بفيلمها) انتقلت إلى
 * `SystemChrome` تلفّ هذه الصفحة وكل صفحة نظام من الجذر، مرّةً واحدة خارج
 * انتقال المسارات. وهذه الصفحة محتواها وحده: العنوان المخفيّ والصفوف.
 * (ونسخ الأمرُ عبارةَ D5 «وبقية الصفحات على شريطها الأيمن»: الشريط يسارًا في
 * كل صفحة.)
 *
 * ## الصفوف بترتيبها (المواصفة §4.0)
 *
 *   الترويسة ← المؤشرات السبعة ← الصدر (الخريطة ≈ ٥/٧ · سَدِيد ≈ ٢/٧)
 *   ← التشغيل (٤ بطاقات) ← التحليلات (٤ بطاقات) ← الخاتمة ← سطر الإفصاح.
 *
 * ## الحركة (أمر المالك ٢٠٢٦/١٠/١٧ — ناسخٌ لـ«بطاقات الرئيسية ساكنة»)
 *
 * دخولٌ متدرّج للمؤشرات والصدر، وظهورٌ عند التمرير لما تحت الطيّة، ورفعةٌ
 * وضغط — CSS وحده في `styles/home/home-motion.css`، اختياريٌّ لمن لم يطلب
 * السكون، والصفحة مكتملةٌ من أوّل إطار بلا حركة. الطفو الدائم يبقى ممنوعًا.
 * الحارس: `src/components/home/home-motion.contract.test.ts`.
 *
 * كل صفٍّ مكوّنٌ في `src/components/home/` يُستورد من هنا وحدها، وكلّها تقرأ
 * من `home-reads.ts` (مفاتيح مشتركة: رقمٌ واحد لا طلبان) وتبني على
 * `home-primitives.tsx` (البطاقة والحالات الثلاث). والإيقاع بين الصفوف ملك
 * الحاوية (`.nx-home-arrange` في `styles/home/home-layout.css`)، لا هوامش الصفوف.
 *
 * ## الصدق العددي (المادة ٢٧) — والإفصاح (الطبقة ٤)
 *
 * ما لم يُقَس يُقرأ «لم يُقَس»؛ لا رقم صفري يوهم بقياس وقع. وسطر الإفصاح في
 * الذيل هو الطبقة الوحيدة الباقية بعد رفع الشارات (٢٠٢٦/٠٨/١١) — يقول إن
 * الأرقام من المصدر الحيّ متى وصل وإلا فمن المحاكاة المرجعية المدمجة.
 */
