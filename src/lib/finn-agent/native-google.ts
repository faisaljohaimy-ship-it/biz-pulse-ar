/** Native Google sign-in for FNN. No hosted-builder OAuth or client-side owner grants. */
export const FNN_PATH = "/fnn";

export function finnGoogleOptions(origin: string) {
  const base = new URL(origin);
  const local = base.hostname === "localhost" || base.hostname === "127.0.0.1";
  if (
    base.username ||
    base.password ||
    (base.protocol !== "https:" && !(local && base.protocol === "http:"))
  ) {
    throw new Error("unsafe_auth_origin");
  }
  return {
    provider: "google" as const,
    options: {
      redirectTo: new URL(FNN_PATH, base.origin).href,
      skipBrowserRedirect: true,
      queryParams: { prompt: "select_account" },
    },
  };
}

/** Bound discovery/authorization, without depending on newer AbortSignal helpers. */
export async function withFinnDeadline<T>(pending: PromiseLike<T>, ms = 8_000): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([
      Promise.resolve(pending),
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => reject(new Error("fnn_timeout")), ms);
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

export function googleProviderEnabled(settings: unknown): boolean {
  if (!settings || typeof settings !== "object") return false;
  const external = (settings as { external?: unknown }).external;
  return (
    !!external && typeof external === "object" && (external as { google?: unknown }).google === true
  );
}

/** Accept only the native Auth authorize URL generated by the SDK. Never an arbitrary next URL. */
export function verifiedGoogleAuthorizeUrl(raw: string | null, origin: string): string {
  if (!raw) throw new Error("missing_auth_url");
  const url = new URL(raw);
  const local = url.hostname === "localhost" || url.hostname === "127.0.0.1";
  if (
    url.username ||
    url.password ||
    (!url.hostname.endsWith(".supabase.co") && !local) ||
    (url.protocol !== "https:" && !(local && url.protocol === "http:")) ||
    !url.pathname.endsWith("/auth/v1/authorize") ||
    url.searchParams.get("provider") !== "google" ||
    url.searchParams.get("redirect_to") !== finnGoogleOptions(origin).options.redirectTo
  )
    throw new Error("invalid_auth_url");
  return url.href;
}

export function finnGoogleError(error: unknown, ar: boolean): string {
  const code = error instanceof Error ? error.message : "";
  if (code === "google_not_configured") {
    return ar
      ? "دخول Google غير مهيّأ في خدمة الهوية بعد. يلزم تفعيل Google وإضافة رابط العودة الخاص بفنن."
      : "Google sign-in is not configured yet. Enable the provider and add the FNN return URL.";
  }
  if (code === "fnn_timeout") {
    return ar
      ? "انتهت مهلة التحقق. أعد المحاولة؛ لم تُمنح أي صلاحيات."
      : "Verification timed out. Retry; no access was granted.";
  }
  return ar
    ? "تعذّر إكمال الدخول عبر Google. أعد المحاولة من Safari أو Chrome؛ لم تُمنح أي صلاحيات."
    : "Google sign-in could not complete. Retry in Safari or Chrome; no access was granted.";
}

/** OAuth errors are untrusted; show fixed copy rather than reflecting their description. */
export function hasFinnOAuthError(href: string): boolean {
  const url = new URL(href);
  const hash = new URLSearchParams(url.hash.replace(/^#/, ""));
  return ["error", "error_code", "error_description"].some(
    (key) => url.searchParams.has(key) || hash.has(key),
  );
}
