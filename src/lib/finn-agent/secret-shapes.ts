/**
 * أنماط أسرارٍ معروفة (رموز GitHub · مفاتيح sk- · أسرار Supabase · JWT) — **مصدرٌ واحد** لكل ما
 * يعرضه فِن من نصٍّ لم يكتبه بنفسه: أدوات القراءة (`cleanText`) وأداة المعرفة والرد المحلّي.
 *
 * نقيّةٌ بلا بيئةٍ ولا شبكة. وهي دفاعٌ ثانٍ لا أول: الحقول المعروضة تُقيَّد بالشكل أصلًا؛ هذا
 * يلتقط ما تسرّب في عنوانٍ أو مقتطفٍ فلا يصل النموذج ولا المالك.
 */
export const SECRET_SHAPES =
  /\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-[A-Za-z0-9_-]{16,}|sb_secret_[A-Za-z0-9_-]{16,}|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,})\b/g;

/** يحجب كل شكل سرٍّ معروف في النصّ بعلامةٍ ثابتة. */
export function maskSecrets(text: string): string {
  return text.replace(SECRET_SHAPES, "[محجوب]");
}
