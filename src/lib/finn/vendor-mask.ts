/**
 * قناع أسماء المزوّدين — مصدر واحد للعميل وللحارس.
 *
 * ## العطل الذي أنشأ هذا الملف
 *
 * `FinnCopilot` يمسح أسماء المزوّدين من نصّ المساعد قبل عرضه — وهي سياسة
 * صحيحة: المستخدم التنفيذي لا يُعرَض عليه اسم مورّد. لكن الخادم كان يكتب
 * ردّه المضمون **بتلك الأسماء نفسها**:
 *
 *   «محرك Gemini الخاص بـFINN غير مهيأ… فعّل GEMINI_API_KEY ثم أعد المحاولة»
 *
 * فيمسح القناعُ `Gemini` و`GEMINI_API_KEY` (النمط `gemini[\w.-]*` يبتلع
 * `_API_KEY` كاملًا)، ويصل إلى الشاشة جملةٌ مكسورة:
 *
 *   «محرك الخاص بFINN غير مهيأ… فعل ثم أعد المحاولة»
 *
 * لا الخادم مخطئ ولا القناع؛ الخطأ أنهما لا يعرف أحدهما الآخر. الاستجابة
 * الخام سليمة تمامًا — قِيست بـcurl — والكسر يقع في العرض وحده، فلا يظهر
 * في أي اختبار خادم.
 *
 * ## القاعدة المستخلَصة
 *
 * **كل نصّ يكتبه الخادم ليقرأه المستخدم يجب أن يعبر القناع دون تغيير.**
 * وهذا ما يحرسه `assertVendorSafe` في الاختبار: لا يكفي أن تُصاغ الجملة
 * جيّدًا اليوم — يجب أن يسقط البناء إن أُعيد اسم مزوّد إليها غدًا.
 */

/**
 * أسماء المزوّدين ونماذجهم كما تُمسح من نصّ المساعد.
 *
 * `gemini[\w.-]*` يلتقط اسم المزوّد ومفاتيحه معًا عمدًا — فلا يتسرّب
 * `GEMINI_API_KEY` إلى الشاشة. ولهذا بالذات لا يجوز أن يرد في نصّ مُصاغ.
 */
export const VENDOR_MASK_RE =
  /\b(openai|anthropic|google|xai|mistral|gpt-\d[\w.-]*|claude-\d[\w.-]*|gemini[\w.-]*|grok[\w.-]*)\b/gi;

/** هل يمرّ النصّ عبر القناع دون أن يفقد حرفًا؟ */
export function isVendorSafe(text: string): boolean {
  return text.replace(VENDOR_MASK_RE, "") === text;
}

/** ما الذي سيمسحه القناع من هذا النصّ (للتشخيص وللرسائل في الاختبار). */
export function vendorMatches(text: string): string[] {
  return [...text.matchAll(VENDOR_MASK_RE)].map((m) => m[0]);
}
