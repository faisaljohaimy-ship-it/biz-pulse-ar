import { createContext, useCallback, useContext, useEffect, useState, type ReactNode } from "react";

/**
 * وضعا سَدِيد — **الداكن دائمًا عند البدء، والفاتح اختيارٌ بالأيقونة** (أمر المالك
 * ٢٠٢٦/١٠/٢٤ بنصّه: «اجعل النظام يبدأ بالوضع الليلي أو الداكن دائماً مع إمكانية
 * تغييره من الأيقونة للفاتح»)، ناسخًا N1 «الفاتح أساسًا» (٢٠٢٦/١٠/١٤) الذي نسخ بدوره
 * «الداكن أساسًا» (٢٠٢٦/٠٨/٠٦، D1 ٢٠٢٦/١٠/١٣). والأقسام التي تذكر «الفاتح أساسًا»
 * أدناه تاريخٌ للقرارات السابقة لا حكمٌ قائم.
 *
 * ## ما يعنيه «دائمًا» (٢٠٢٦/١٠/٢٤)
 *
 * كل زيارةٍ جديدة تبدأ داكنة، **لا يُقرأ تفضيل نظام التشغيل ولا اختيارٌ قديمٌ في
 * `localStorage`**. وإن بدّل الزائر إلى الفاتح بالأيقونة فاختياره يسري **على هذه
 * الجلسة** (`sessionStorage`) فلا يرتدّ داكنًا مع كل تنقّلٍ أو إعادة تحميل — ثم تبدأ
 * الجلسة التالية داكنة من جديد. كان الاختيار يُحفظ في `localStorage` فيبقى فاتحًا
 * عند كل زيارة، وهذا ما أُلغي. والمفتاح المخزَّن القديم يُترك ولا يُقرأ.
 *
 * ## ما الذي تغيّر ولماذا
 *
 * أُلغي المبدّل صباحًا لأن الوضع الفاتح كان مكسورًا: **١٢٨٧ قيمة داكنة
 * مكتوبة يدويًّا في ١٤٥ ملفًا** خارج طبقة الرموز، فالوضع الفاتح كان يقلب
 * الرموز ولا يقلبها. ثم طلب المالك عودة المبدّل على الجوال وكل الأجهزة،
 * فعاد — لكن ليس كما كان: عودته وحدها كانت ستعيد العطل نفسه.
 *
 * الجسر في `styles.css` هو ما يجعلها عودةً صالحة. لبّه سطرٌ واحد:
 * Tailwind v4 يُصرّف **كل** أدوات الأبيض عبر `var(--color-white)` —
 * `text-white` و`text-white/60` و`border-white/10` و`bg-white/5` جميعها.
 * فإعادة تعريف هذا المتغيّر وحده تحت `.light` تقلب ١٠٧٢ موضعًا دفعةً
 * واحدة **مع حفظ تدرّج الشفافية في كل موضع**. لا تعديل على ملف مكوّن
 * واحد، ولا خطر على الوضع الداكن لأن القاعدة محصورة بـ`.light`.
 *
 * ## الأساس فاتح (N1 — ناسخ «الأساس يبقى داكنًا»)
 *
 * أعاد المالك إرسال تصميم الرئيسية المرجعي بـ«طبق الصورة بحذافيرها»،
 * والتصميم فاتح، فاختار «الفاتح كما في الصورة (موصى به)» افتراضيًّا للنظام
 * كلّه (`docs/design/10-home-command-center-prompt.md` §2.1). فمن لم يختر
 * يحصل على الفاتح عند أول زيارة، والاختيار المحفوظ يُحترم دائمًا.
 *
 * **والداكن لم يُلغَ:** يبقى على بُعد ضغطة واحدة، وسطحَ صحّةٍ كاملًا لا قشرة
 * — كل فحص يُشغَّل في الوضعين وكل لقطة تُلتقط مرتين (المواد ٣٢–٣٤).
 * ولا قراءة لتفضيل نظام التشغيل: الافتراضي قرارُ مالكٍ لا استنتاج.
 *
 * ## المبدّل: أُزيل يومًا ثم عاد بموضعٍ محدَّد
 *
 * ٢٠٢٦/٠٩/١٠ أمر المالك بإزالة أيقونات تغيير الوضع والجرس والرجوع والهوم
 * «من النظام كاملًا» فسقط الزرّ وسقط معه `toggle`، وبقي المحرّك وحده —
 * إذ المأمور به إزالة العلامة لا نظام الألوان.
 *
 * ثم أمر ٢٠٢٦/٠٩/١١ بإعادته: «أضف أيقونة زر تغيير الوضعية ثابتة في أعلى
 * الصفحة الرئيسية». فعاد الزرّ و`toggle` معه — **بنطاقٍ أضيق مما كان**:
 * الرئيسية وحدها، لا كل مسار. موضعه في `components/nav/TopBar.tsx`.
 *
 * وبقاءُ المحرّك خلال يوم الغياب هو ما جعل العودة سطرين: لم تُمسّ طبقة
 * الوضعين ولا القراءة قبل أول رسم، فلم يسقط فحص الوضعين
 * (`tests/e2e/14-lottie-theme.spec.ts`) ولا سقفُ المادة ٣٢.
 */
export type Theme = "dark" | "light";

/** ما يبدأ به كل زائر: الداكن (أمر المالك ٢٠٢٦/١٠/٢٤). والفاتح اختيارٌ صريح يسري على الجلسة. */
export const DEFAULT_THEME: Theme = "dark";

/** المفتاح نفسه الذي يقرأه السكربت السابق لأول رسم في `__root.tsx` — في `sessionStorage` لا `localStorage`. */
export const THEME_KEY = "theme";

/**
 * الوضع الذي تعنيه قيمةٌ مخزَّنة — **القاعدة الوحيدة، وللسكربت نسختها.**
 *
 * السكربت السابق لأول رسم في `__root.tsx` لا يستورد شيئًا (يجري قبل أي
 * حزمة)، فيكتب القاعدة نفسها نصًّا: «فاتح إن حُفظ `light` صراحةً في هذه الجلسة، وإلا
 * الافتراضي (داكن)». فإن افترقت النسختان رأى المستخدم وضعًا عند أول رسم ثم قفز
 * إلى غيره بعد الترطيب. حارس `theme/theme-contract.test.ts` يشغّل السكربت
 * الفعلي ويقارنه بهذه الدالة على كل قيمة.
 */
export function resolveStoredTheme(stored: string | null): Theme {
  return stored === "light" || stored === "dark" ? stored : DEFAULT_THEME;
}

const ThemeCtx = createContext<{
  theme: Theme;
  setTheme: (t: Theme) => void;
  toggle: () => void;
} | null>(null);

/** يكتب الوضع على الجذر — نقطة التطبيق الوحيدة، فلا يتنازع كاتبان. */
function apply(theme: Theme) {
  const root = document.documentElement;
  root.classList.toggle("light", theme === "light");
  root.classList.toggle("dark", theme === "dark");
  root.style.colorScheme = theme;
}

export function ThemeProvider({ children }: { children: ReactNode }) {
  // تبدأ بالافتراضي كما يرسمها الخادم تمامًا، فلا يختلف أول رسمٍ على العميل
  // عن الخادم. السكربت السابق لأول رسم يكون قد وضع الصنف الصحيح على `<html>`
  // قبل ذلك، والمزامنة أدناه تُلحق حالة React به بلا وميض.
  const [theme, setThemeState] = useState<Theme>(DEFAULT_THEME);

  useEffect(() => {
    let stored: string | null = null;
    try {
      stored = sessionStorage.getItem(THEME_KEY);
    } catch {
      /* تخزين محظور — يبقى الافتراضي لهذه الجلسة. */
    }
    const next = resolveStoredTheme(stored);
    setThemeState(next);
    apply(next);
  }, []);

  const setTheme = useCallback((next: Theme) => {
    setThemeState(next);
    apply(next);
    try {
      sessionStorage.setItem(THEME_KEY, next);
    } catch {
      /* تخزين محظور — الاختيار يسري لهذه الصفحة وحدها. */
    }
  }, []);

  // **عاد `toggle` بعودة زرّه (أمر المالك ٢٠٢٦/٠٩/١١).** سقط يومًا مع
  // المبدّل لئلّا يبقى خطّافًا موصولًا بلا زرّ، ثم أمر المالك بإعادة
  // المبدّل إلى أعلى الرئيسية فعاد معه.
  //
  // ويقرأ **صنف الجذر** لا حالة React: الحالة تبدأ بالافتراضي (داكنة)
  // دائمًا لتطابق ما يرسله الخادم، بينما السكربت السابق لأول رسم يكون قد
  // وضع الصنف الصحيح فعلًا — فقراءةُ الحالة تقلب الوضع الخطأ عند أول ضغطة
  // لمن اختار الفاتح.
  const toggle = useCallback(
    () => setTheme(document.documentElement.classList.contains("light") ? "dark" : "light"),
    [setTheme],
  );

  return <ThemeCtx.Provider value={{ theme, setTheme, toggle }}>{children}</ThemeCtx.Provider>;
}

export function useTheme() {
  const ctx = useContext(ThemeCtx);
  if (!ctx) throw new Error("useTheme must be inside ThemeProvider");
  return ctx;
}
