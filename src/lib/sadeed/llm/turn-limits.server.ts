/**
 * سقف خطوات الأدوات لدور الدردشة (٢٠٢٦/١١/٠٣) — **التخفيض اختياريّ (opt-in)** بقرار النشر على مرحلتين.
 *
 * ## لماذا
 *
 * كل خطوة أدوات جولة نموذجٍ كاملة متسلسلة (التعليمات الثابتة ومخططات الأدوات تُعاد في كل
 * خطوة) ثم استعلام قاعدة بلا مهلة خاصة. السقف القديم 8 لكل الأوضاع يتيح لسؤالٍ عاديّ ثمانيَ
 * جولات، وعدد الخطوات الفعلي في الإنتاج **غير مقيس بعد** (يقيسه `steps[]` في سطر
 * `[api/chat] timing`) — فلا يُنسب لهذا السقف تحسّنٌ لم يُقس.
 *
 * ## النشر على مرحلتين (قرار حارس الجودة بعد نقض الإصدار)
 *
 * ضوابط المالك لمسار الإجابة (خطوة صغيرة · اختبارات · تصريح الحارس · قياس قبل/بعد) لا تتحقق
 * حين تُنشر عدّة تغييرات سلوكية دفعةً واحدة. فالمرحلة ١ (هذا الكود) **لا تخفّض شيئًا**: الافتراض
 * 8 لكل الأوضاع كما كان، ولا `prepareStep` في نداء `generateText` (انظر `guardsLastStep`) —
 * فيطابق الطلب القديم. ويُخفَّض السقف بمتغيّر البيئة وحده بعد قياس «قبل»، وهذه المرحلة ٢
 * ولا تقع في الكود.
 *
 * ## القواعد
 *
 * - النص والصوت والعميق: **8** افتراضًا (القديم).
 * - `SADEED_MAX_STEPS_TEXT` (عددٌ صحيح 2..8) **يخفّض** سقف النص والصوت **وحدهما** اختياريًّا،
 *   ويُقرأ عند كل طلب؛ ما خرج عن النطاق أو لم يكن عددًا صحيحًا خالصًا يُهمَل (يعود 8) — لا يُقصّ
 *   إلى الحدّ. والعميق 8 دائمًا. وتغيير المتغيّر على Vercel يلزمه إعادة نشر ليراه نشرٌ قائم.
 * - المحوّل الاختياري (OpenAI) سقفه 2 في `chat.ts` ولا يمرّ من هنا.
 */

export const MAX_STEPS_TEXT_DEFAULT = 8;
export const MAX_STEPS_DEEP = 8;
const MAX_STEPS_TEXT_MIN = 2;
const MAX_STEPS_TEXT_MAX = 8;

type EnvLike = Record<string, string | undefined>;

/** سقف الخطوات لهذا الدور (غير المحوّل الاختياري): 8 ما لم يخفّضه المالك للنص والصوت. */
export function maxStepsFor(replyMode: string, env: EnvLike = process.env): number {
  if (replyMode === "deep") return MAX_STEPS_DEEP;
  const raw = env.SADEED_MAX_STEPS_TEXT?.trim() ?? "";
  if (/^\d{1,2}$/.test(raw)) {
    const n = Number(raw);
    if (n >= MAX_STEPS_TEXT_MIN && n <= MAX_STEPS_TEXT_MAX) return n;
  }
  return MAX_STEPS_TEXT_DEFAULT;
}

/**
 * هل يلزم `prepareStep` لهذا السقف؟ **فقط حين خفّض المالك السقف دون 8** (`maxSteps < 8`).
 * عند 8 (الافتراض القديم) لا يُمرَّر `prepareStep` إطلاقًا فيطابق طلبُ `generateText` الطلبَ
 * القديم — وهذا شرط «السلوك الافتراضي لا يتغيّر» في المرحلة ١. (والعميق دائمًا 8 فلا يحمله.)
 */
export function guardsLastStep(maxSteps: number): boolean {
  return maxSteps < MAX_STEPS_DEEP;
}

/**
 * `prepareStep` لـ`generateText`: عند **آخر خطوةٍ** يسمح بها السقف تُمنع الأدوات
 * (`toolChoice: "none"`) فيكتب النموذج جوابه من نتائج الخطوات السابقة. يُستعمل خلف
 * `guardsLastStep(maxSteps)` وحده، أي حين يكون السقف مخفَّضًا.
 *
 * ## لماذا (نتيجة مباشرة لتخفيض السقف دون 8)
 *
 * `stepCountIs(n)` يوقف التوليد بعد الخطوة n **أيًّا كان ما أنتجته**. فإن كانت الخطوة الأخيرة
 * نداءَ أدوات فنصّ الدور فارغ: أُنفقت الأدوات واستعلاماتها ولم يصل المستخدم جوابٌ — وكلما خفّ
 * السقف زاد احتمال ذلك. هذا يضمن أن آخر خطوة مسموحة تُنتج نصًّا، ولا يغيّر شيئًا في دورٍ
 * انتهى قبل السقف. (عند السقف القديم 8 لا يُمرَّر؛ فاحتمال الوقوف على نداء أدواتٍ ونصّه فارغ
 * عند 8 قائمٌ كما كان قبل هذا العمل، ولم يُعالَج هنا عمدًا حفاظًا على التكافؤ.)
 *
 * `stepNumber` يبدأ من الصفر، فآخر خطوة مسموحة رقمها `maxSteps - 1`.
 */
export function lastStepAnswers(maxSteps: number) {
  return ({ stepNumber }: { stepNumber: number }) =>
    stepNumber >= maxSteps - 1 ? { toolChoice: "none" as const } : undefined;
}
