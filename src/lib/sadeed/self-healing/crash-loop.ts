/**
 * كاسر دورة الأعطال (الدستور، المادة XIII) — الجانب الذي يعمل بعد الترطيب.
 *
 * السكربت السابق للترطيب في `src/routes/__root.tsx` يزيد عدّادًا في
 * `sessionStorage` عند كل خروجٍ غير نظيف (انظر «الدرس الثالث» أدناه)، ويدخل
 * `html.safe-mode` متى بلغ ٢. وهذا
 * الملف يملك الطرف الآخر من العقد: **متى يُعدّ الإقلاع سليمًا فيُمحى العدّاد**،
 * و**كيف يُقرأ الوضع الآمن** في الكود الثقيل.
 *
 * ## درس ٢٠٢٦/١٠/١٤ (P0 — سفاري iOS: «حدثت مشكلة بشكل متكرر»)
 *
 * كان العدّاد يُمحى لحظة أول commit لـReact. فأيّ انهيار **بعد** الترطيب —
 * وهو نوع انهيار iOS الشائع (jetsam: ذاكرة/GPU بعد بدء الفيديو وفكّ الصور
 * وحلقات `requestAnimationFrame`) — يجد العدّاد صفرًا عند كل إقلاع، فلا يبلغ
 * ٢ أبدًا، ولا يدخل الوضع الآمن، ويصل سفاري إلى صفحته القاتلة.
 *
 * القاعدة الآن: **الإقلاع سليم بعد بقاءٍ مرئيّ لا بعد أول رسم.**
 *
 * ## والدرس الثاني في اليوم نفسه: الانهيار بعد ٢٠ ثانية — «الخروج غير النظيف»
 *
 * المهلة وحدها لا تكفي: تمحو العدّاد بعد ٢٠ ثانية (والنبضة بعد ٣٠)، فمن فتح
 * لوحة سَدِيد بعدها فانهارت الصفحة أقلع من جديد بـn=1 (وضعٌ عاديّ)، ففتحها
 * ثانيةً فانهارت ثانيةً — وتلك صفحة سفاري القاتلة.
 *
 * فالسكربت السابق للترطيب يحفظ علَم الحياة `ALIVE_KEY` = '1' ما دامت الصفحة
 * ظاهرة، ويمحوه عند `pagehide` وعند الإخفاء، ويعيده عند الظهور و`pageshow`.
 * فإن وجده الإقلاعُ التالي '1' فالحياة السابقة ماتت بلا `pagehide` وهي ظاهرة —
 * وذلك jetsam بعينه — فتُحسب ضربة **أيًّا كان عمرها**: n = max(n, 1) + 1،
 * أي الوضع الآمن في الإقلاع الذي يلي أوّل انهيار. والخروج النظيف (إعادة
 * تحميل، تنقّل، عودة OAuth) يمرّ بـ`pagehide`، والقتل في الخلفية يقع بعد
 * الإخفاء — فلا يُحسب أيٌّ منهما. والمستمعون في السكربت نفسه لا بعد الترطيب:
 * مغادرةٌ قبل الترطيب تمحو العلَم كذلك.
 *
 * فلم تعد المهلة تقرّر **هل يُحسب الانهيار**؛ عملها الوحيد **غفران الضربات
 * القديمة** بعد بقاءٍ سليم.
 *
 * ## والدرس الثالث: العدّاد يعدّ الخروج غير النظيف وحده
 *
 * بقي السكربت بعد علَم الحياة يزيد العدّاد ١ عند **كل** إقلاعٍ نظيف (`n+1`)،
 * ولم يعد شيءٌ يمحوه عند الـcommit — فكلّ خروجٍ نظيف قبل ٢٠ ثانية مرئيّة صار
 * ضربة. قِيس بالسكربت المشحون نفسه في jsdom مع `pagehide` بين إقلاعين: إعادة
 * تحميلٍ سريعة واحدة ⇐ n=2 ⇐ الوضع الآمن؛ والثانية ⇐ n=3 ⇐ محو التخزين المؤقّت
 * و«الشفاء الصلب» بإعادة تحميلٍ تلقائية تستهلك شفاء الجلسة الوحيد. وذلك
 * سحبتا تحديث، أو عودة OAuth أسرع من ٢٠ ثانية، أو زرّ «إعادة التحميل» في حدود
 * الخطأ — على سطح المكتب كذلك، فالسكربت لا يعرف جهاز الإدخال.
 *
 * وعلَم الحياة يلتقط وحده كل انهيارٍ يقع بعد السكربت (العملية الميتة لا
 * تطلق `pagehide`)، فلم يبقَ للزيادة العمياء إلا الإنذار الكاذب. فالإقلاع
 * النظيف يُبقي n كما هو. ومسار «الشفاء الصلب» سليم: يُبقي n ≥ ٣، وإعادة
 * تحميله النظيفة تعيد فرض الوضع الآمن؛ والانهيار الحقيقي يعطي n ≥ ٢ في
 * الإقلاع التالي.
 *
 * ## لماذا ٢٠ ثانية
 *
 *   • **أطول من نافذة الانهيار عند الفتح.** ما يبدأ مع الصفحة يبدأ خلال
 *     ثوانٍ: الترطيب، ثم الوحدات الكسولة (المراقب والمعالج الدائم وفحص
 *     الذاكرة عند ٢ ث)، ثم مشغّل Lottie عند الخمول (مهلة ≤ ٢ ث)، ثم فيلم
 *     الخلفية وفكّ صور البورتريه، وأول فتحٍ للوحة سَدِيد عند المستخدم
 *     المستعجل. ضربةٌ قائمة لا تُغفر داخل هذه النافذة، فانهياران فيها
 *     يتصاعدان إلى n=3 و«الشفاء الصلب».
 *   • **قصيرة بما يكفي ألّا يبقى المتعافي في القشرة الساكنة.** الوضع الآمن
 *     يُعاد فرضه عند كل إقلاعٍ نظيف ما دام n ≥ ٢؛ فمهلةٌ طويلة تُبقي من نجا
 *     من انهيارٍ واحد بلا فيديو ولا ظلال عبر إعادات تحميله.
 *   • **وهي وحدها تملك الغفران.** نبضة المعالج الدائم (٣٠ ث) كانت تمحو
 *     العدّاد كذلك، وهي على زمن الحائط لا الزمن المرئيّ: تفحص الظهور لحظة
 *     إطلاقها فقط، فتبويبٌ حُمِّل في الخلفية (مؤقّتات سطح المكتب تجري فيها)
 *     يُغفر له عند أوّل نبضةٍ بعد ظهوره — ربما بعد ثانيةٍ مرئيّة واحدة. فنُزع
 *     المحو منها؛ وما بعد اكتمال المهلة لا شيء يُمحى أصلًا، فالعدّاد لا
 *     يكتبه إلا السكربت عند الإقلاع.
 *
 * ## لماذا «مرئيّ»
 *
 * الصفحة المخفيّة لا يُرسم منها شيء — مؤقّتاتها تُعلَّق على iOS وعمل الـGPU
 * متوقّف — فبقاؤها حيّةً في الخلفية لا يشهد بأنّ الرسم آمن. فالمدّة تُحسب
 * تراكميًّا على الزمن المرئيّ وحده: تتوقّف عند الإخفاء وتستأنف عند العودة.
 * وتُقاس بساعةٍ رتيبة (`performance.now()`) لا بـ`Date.now()`: تعديل ساعة
 * الجهاز (NTP أو يدويًّا) والمؤقّت مسلَّح كان يطيل الباقي (زمنٌ منقضٍ سالب) أو
 * يُصفّره فيغفر مبكّرًا.
 *
 * ## حدٌّ معروف — مقبول وموثَّق، لا مُعالَج: تكرار التبويب
 *
 * «تكرار التبويب» (Chrome/Edge) و`window.open` بلا `noopener` ينسخان
 * `sessionStorage` بما فيه `ALIVE_KEY` = '1' من صفحةٍ ما زالت حيّة. فيُقلع
 * المكرَّر بـn = max(n, 1) + 1 ≥ ٢ ويدخل الوضع الآمن على سطح المكتب (الفيديو
 * واللوحات مخفيّة، والظلال والانتقالات ساقطة) لحياة صفحةٍ واحدة؛ وإن كان
 * عدّاد المصدر ٢ بلغ المكرَّر ٣ فجرى «الشفاء الصلب» بإعادة تحميلٍ تلقائية.
 * والعلاج المرشَّح — تجاهل العلَم حين نوع التنقّل `navigate`
 * (`performance.getEntriesByType('navigation')`) و`history.length > 1` —
 * **لم يُشحن**: لم يُقَس نوع التنقّل في إعادة التحميل التلقائية بعد انهيار
 * سفاري على آيفون حقيقي، وحكمٌ غير مقيس هنا قد يُسكت كشف الانهيار الحقيقي
 * نفسه. يُقاس أولًا ثم يُقرَّر.
 *
 * SSR-safe: لا وصول إلى `window` أو `document` إلا داخل الدوالّ.
 */

/** مفتاح العدّاد — يكتبه السكربت السابق للترطيب ويقرؤه المعالج الدائم. */
export const BOOT_ATTEMPTS_KEY = "nexios-boot-attempts";

/**
 * علَم «الحياة الجارية» — يكتبه السكربت السابق للترطيب ويمحوه وحده (انظر
 * «الخروج غير النظيف» أعلاه). لا يُمحى مع العدّاد: غفران الضربات القديمة لا
 * يمسّ شاهدَ الحياة الحاضرة، ولو مُحي معه لعاد الانهيار بعد المهلة لا يُحسب.
 */
export const ALIVE_KEY = "nexios-alive";

/** الصنف الذي يضعه الكاسر على `<html>` — المرجع الحيّ الوحيد للوضع الآمن. */
export const SAFE_MODE_CLASS = "safe-mode";

/** الزمن المرئيّ الذي يجعل الإقلاع سليمًا (انظر «لماذا ٢٠ ثانية» أعلاه). */
export const HEALTHY_UPTIME_MS = 20_000;

/**
 * هل الصفحة في الوضع الآمن الآن؟
 *
 * يقرأ الصنف على `<html>` لا علَم الجلسة `nexios-safe-mode`: الصنف حالة هذه
 * الصفحة (يضعه الكاسر قبل الترطيب، أو المعالج الدائم عند ضغط الذاكرة)، أمّا
 * العلَم فأثرٌ مسجَّل لا يُمحى، ولو قُرئ لبقيت الصفحة ساكنةً بعد أن شُفيت.
 */
export function isSafeMode(): boolean {
  if (typeof document === "undefined") return false;
  try {
    return document.documentElement.classList.contains(SAFE_MODE_CLASS);
  } catch {
    return false;
  }
}

/** يمحو عدّاد الإقلاع — بلا رمي أبدًا (تخزين محجوب في التصفّح الخاص). */
export function clearBootAttempts(): void {
  try {
    window.sessionStorage.removeItem(BOOT_ATTEMPTS_KEY);
  } catch {
    /* التخزين محجوب: لا عدّاد أصلًا */
  }
}

/**
 * ساعةٌ رتيبة للزمن المرئيّ: لا تتراجع ولا تقفز مع ضبط ساعة الجهاز.
 * و`Date.now()` احتياطٌ لبيئةٍ بلا `performance` وحدها.
 */
function monotonicNow(): number {
  return typeof performance !== "undefined" && typeof performance.now === "function"
    ? performance.now()
    : Date.now();
}

/**
 * يُسلِّح مؤقّت «الإقلاع السليم»: بعد `uptimeMs` من الزمن المرئيّ المتراكم
 * يُمحى العدّاد. ويعيد دالّة نزعٍ تُستدعى عند الفكّ — نزعٌ قبل المهلة يُبقي
 * الضربة قائمة، فالإقلاع لم يُثبت سلامته.
 *
 * وهو **المالك الوحيد للغفران** بعد الإقلاع (انظر «وهي وحدها تملك الغفران»
 * أعلاه).
 *
 * لا يمحو شيئًا متزامنًا: الاستدعاء نفسه لا يلمس التخزين.
 */
export function armHealthyBootReset(uptimeMs: number = HEALTHY_UPTIME_MS): () => void {
  if (typeof window === "undefined" || typeof document === "undefined") return () => {};

  let remaining = Math.max(0, uptimeMs);
  let startedAt = 0;
  let timer: number | undefined;
  let finished = false;

  const pause = () => {
    if (timer === undefined) return;
    window.clearTimeout(timer);
    timer = undefined;
    remaining = Math.max(0, remaining - (monotonicNow() - startedAt));
  };

  const resume = () => {
    if (finished || timer !== undefined) return;
    startedAt = monotonicNow();
    timer = window.setTimeout(() => {
      timer = undefined;
      finished = true;
      document.removeEventListener("visibilitychange", onVisibility);
      clearBootAttempts();
    }, remaining);
  };

  function onVisibility() {
    if (document.visibilityState === "visible") resume();
    else pause();
  }

  document.addEventListener("visibilitychange", onVisibility);
  onVisibility();

  return () => {
    pause();
    finished = true;
    document.removeEventListener("visibilitychange", onVisibility);
  };
}
