/**
 * سيناريو المقدّمة السينمائية — ٣٠ ثانية قبل الصفحة الرئيسية.
 *
 * أمر المالك ٢٠٢٦/٠٨/٢٨: «مقدمة ترحيبية وتعريفية للنظام مذهلة لمدة ٣٠ ثانية
 * كمقدمة سينمائية في بداية النظام قبل الصفحة الرئيسية… مع وجود زر لكتم
 * الصوت الترحيبي».
 *
 * **وهذا ناسخٌ لِما كان مكتوبًا في `__root.tsx`:** «no cinematic welcome
 * overlay — the homepage renders directly». تلك قاعدةٌ سابقة صريحة، وأمر
 * المالك اليوم صريحٌ مثلها وأحدث — فالنصّ الأحدث يسود، ويُوثَّق النسخ ولا
 * يُطمس.
 *
 * ── لماذا البيانات هنا لا في المكوّن ──
 * النصّ المنطوق والتوقيت هما ما يُراجَع ويُقاس ويُختبر؛ فصلُهما عن JSX يجعل
 * كل بند منهما قابلًا للفحص بلا تصيير. والحارس يقرأ هذا الملف وحده ليثبت
 * المادة ٢٧: **لا رقم ولا نسبة في النصّ المنطوق**، لأن أي رقم يُنطق على
 * الشاشة الأولى يُقرأ قياسًا وقع — ولم يقع.
 */

/**
 * المدّة الكلّية بالمللي ثانية — **«١٠ ثوانٍ» بأمر المالك ٢٠٢٦/٠٨/٢٨ (ب)**،
 * ناسخًا «٣٠ ثانية» في أمره الأول من اليوم نفسه.
 *
 * والتقصير ليس تنازلًا: مقدّمةٌ تسبق كل جلسة عملٍ يدفعها المستخدم بعد
 * المرّة الأولى، وثلاثون ثانيةً تُدفَع أسرع من عشر. وعشرٌ تكفي الاسمَ
 * والصفةَ وإفصاح المحاكاة — وهي كل ما يلزم قبل الشاشة الأولى.
 */
export const INTRO_TOTAL_MS = 10_000;

/**
 * هندسة الوجه في `‎/sadeed-intro.webp`‎ — **نسبٌ مقيسة لا مقدَّرة.**
 *
 * قِيست باقتصاص الرأس من الأصل (941×1672) عند الصندوق (380,360)-(570,620)
 * وتكبيره ×3، ثم قراءة مواضع الملامح على المقتطع وإرجاعها إلى الأصل:
 *   العينان   y = 360 + (410/780)×260 = 496.7px → 0.297
 *   الفم      y = 360 + (575/780)×260 = 551.7px → 0.330
 *   المركز    x = 380 + (285/570)×190 = 475.0px → 0.505
 *
 * كلّها كسورٌ من مقاس الصورة لا بكسلات: الطبقة تُعرض بأحجام مختلفة على
 * ٣٩٠ و١٢٨٠، فالبكسل المطلق يفترق مع المقاس والنسبة لا تفترق.
 */
export const INTRO_FACE = {
  /** مركز الوجه أفقيًّا. */
  centerX: 0.505,
  /** خطّ العينين — مرساة الرمش. */
  eyesY: 0.297,
  /** مركز الفم — مرساة حركة الشفاه. */
  mouthY: 0.33,
  /** نصف عرض منطقة الفم (كسر من العرض). */
  mouthHalfW: 0.032,
  /** نصف ارتفاع منطقة الفم (كسر من الارتفاع). */
  mouthHalfH: 0.014,
  /** نصف ارتفاع شريط العينين. */
  eyesHalfH: 0.012,
  /** نصف عرض شريط العينين. */
  eyesHalfW: 0.062,
} as const;

export interface IntroBeat {
  /** بداية المشهد بالمللي ثانية من بدء المقدّمة. */
  atMs: number;
  /** سطر الشاشة العربي — يظهر مكتوبًا، ولا يُنطق منه شيء زائد. */
  caption: string;
  /**
   * تقريب الكاميرا في هذا المشهد. 1 = المشهد كاملًا، وما فوقه اقتراب.
   * الاقتراب ليس زينة: الوجه في الصورة الكاملة أصغر من أن تُقرأ عليه حركة
   * الشفاه، فبلا تقريبٍ تصير الحركة تفصيلًا لا يُرى.
   */
  zoom: number;
  /** مرساة التقريب — `face` تُثبّت الوجه في المركز، `full` المشهد كلّه. */
  anchor: "face" | "full";
}

/**
 * المشاهد الستّة. التوقيت من الزمن المنقضي لا من موضع الصوت: نقطة TTS قد
 * تتأخّر أو تسقط كليًّا (لا مفتاح ElevenLabs في بيئة ما)، والمقدّمة يجب أن
 * تسير كاملةً في الحالتين. الصوت يجري **بمحاذاة** الخطّ الزمني لا يقوده.
 */
export const INTRO_BEATS: readonly IntroBeat[] = [
  { atMs: 0, caption: "سَدِيد", zoom: 1.0, anchor: "full" },
  { atMs: 3_000, caption: "مساعدك التنفيذي للأمن الصناعي", zoom: 1.4, anchor: "face" },
  { atMs: 6_800, caption: "بيانات محاكاة مرجعية", zoom: 1.1, anchor: "full" },
] as const;

/**
 * النصّ المنطوق — **جملة واحدة تُطلب مرّة واحدة** من نقطة TTS الخادمية.
 *
 * ولماذا طلبٌ واحد لا ستّة بعدد المشاهد: كل طلب يدفع زمن شبكة وحصّة محدّد
 * معدّل، وستّة طلبات تُسمع فجواتٍ بين الجمل. الطلب الواحد يُنطق متّصلًا.
 *
 * **والمادة ٢٧ محفوظة نصًّا:** لا عدد ولا نسبة ولا إنجاز مقيس هنا — ولا
 * حتى «آلاف البلاغات». وسطر المحاكاة مذكور صراحةً في المنطوق لا في الشاشة
 * وحدها، فالسامع الذي لا يقرأ يسمعه أيضًا.
 */
export const INTRO_NARRATION_AR = [
  "السلام عليكم، أنا سَدِيد —",
  "مساعدك التنفيذي للأمن الصناعي،",
  "عربيٌّ أولًا للقطاع الصناعي السعودي.",
  "وما تراه بيانات محاكاة مرجعية.",
  "لنبدأ.",
].join(" ");

/** المشهد الساري عند لحظة بعينها. */
export function beatAt(elapsedMs: number): IntroBeat {
  let current = INTRO_BEATS[0];
  for (const b of INTRO_BEATS) {
    if (elapsedMs >= b.atMs) current = b;
    else break;
  }
  return current;
}

/** التقدّم من 0 إلى 1 — يقود شريط التقدّم وتلاشي الخروج. */
export function introProgress(elapsedMs: number): number {
  if (elapsedMs <= 0) return 0;
  if (elapsedMs >= INTRO_TOTAL_MS) return 1;
  return elapsedMs / INTRO_TOTAL_MS;
}
