/**
 * وسم المنشئ بصيغه: «أنشأه:» كما كتبه `buildNotes` قبل الإصلاح، و«Entered by»
 * / «Created by» كما ترد أعمدة SAP. يُحذف الوسم وقيمته حتى الفاصل « · » أو
 * نهاية السطر — فالقيمة لا تُعرف حدودها، والحذف المحافظ أسلم من القصّ.
 */
const CREATOR_SEGMENT = /(?:أنشأه|أنشأها|entered\s+by|created\s+by)\s*[:：]\s*[^·\n]*/giu;

/**
 * رمزٌ بشكل «حرفان + عشرة أرقام» — شكل قيم «Entered by» في تصدير IW38 حين
 * لا تكون رقمًا وظيفيًّا. يُحجب أينما ورد في الملاحظات.
 */
const TWO_LETTERS_TEN_DIGITS = /(?<![\p{L}\p{N}])[A-Za-z]{2}\d{10}(?!\p{N})/gu;

export const PERSON_IDENTITY_MASK = "[محجوب]";

/** ملاحظات أمر صيانة بلا هوية أشخاص — الفواصل تُرتَّب بعد الحذف. */
export function stripPersonIdentity(text: string): string {
  return text
    .replace(CREATOR_SEGMENT, "")
    .replace(TWO_LETTERS_TEN_DIGITS, PERSON_IDENTITY_MASK)
    .replace(/(?:[ \t]*·[ \t]*){2,}/g, " · ")
    .replace(/^[ \t]*·[ \t]*|[ \t]*·[ \t]*$/gm, "")
    .trim();
}
