/**
 * أداة التعريف وما يلتصق بها: الأطول أولًا كي لا يُقتطع «وبال» على «ال».
 * «لل» وأخواتها الملتصقة ملتبسة (انظر الترويسة) فتُعامَل مرشّحَين.
 */
const ARTICLE_PREFIXES = [
  "وبال",
  "فبال",
  "وكال",
  "فكال",
  "ولل",
  "فلل",
  "وال",
  "بال",
  "فال",
  "كال",
  "ال",
  "لل",
];

/**
 * تجريد أداة التعريف إلى نقطة ثبات على مقطع مطويّ صارمًا، حين يبقى ثلاثة
 * أحرف فأكثر (فلا يُمسّ «الم»). يعيد مرشّحَين على الأكثر: الجذع، ومعه «ل» +
 * الباقي عند **أول** «لل» جُرّدت (ترويسة الملف: تجريدٌ ثانٍ لـ«لل» لا يقع إلا
 * على سلسلة لامات، وإصداره لكل تجريد كان O(L²)). معرَّضة للاختبار المباشر
 * (الحالات المزروعة في `bm25.test.ts`).
 */
export function articleCandidates(token: string): string[] {
  let t = token;
  let lamCandidate: string | null = null;
  for (;;) {
    const p = ARTICLE_PREFIXES.find((x) => t.startsWith(x) && t.length - x.length >= 3);
    if (!p) break;
    const rest = t.slice(p.length);
    if (lamCandidate === null && p.endsWith("لل")) lamCandidate = `ل${rest}`;
    t = rest;
  }
  return lamCandidate === null ? [t] : [t, lamCandidate];
}

/** كل رقم عشري بأي خطّ (`Nd`): 4 و٤ و۴ — لا `\d` الذي يرى ASCII وحده. */
const ALL_DIGITS = /^\p{Nd}+$/u;
/**
 * هل المقطع سلسلة أرقام بأي خطّ عشري؟ تحتاجه ذراع المتن المبذور لتمييز مطابقةٍ
 * على رقم رمز HCIS وحده («٤» في «SECTOR-04») عن مطابقة على اسم.
 */
export function isDigitRun(token: string): boolean {
  return ALL_DIGITS.test(token);
}
/** «02» و«2» مقطع واحد؛ «0» يبقى «0». يُطبَّق على المقطع الصارم (أرقامه ASCII). */
function canonicalToken(t: string): string {
  return ALL_DIGITS.test(t) ? t.replace(/^0+(?=\d)/, "") : t;
}
function longEnough(t: string): boolean {
  return t.length >= MIN_TOKEN_LENGTH || ALL_DIGITS.test(t);
}

/** سلسلة حروف أو سلسلة أرقام — الحدّ بينهما فاصل (ترويسة الملف). */
const TOKEN_RUN = /\p{L}+|\p{N}+/gu;

/**
 * مقاطع النصّ: الطيّ الخفيف ⇐ سلاسل الحروف والأرقام ⇐ إسقاط كلمات الوصل
 * (بالطيّ الخفيف) ⇐ الطيّ الصارم (مرّةً على النصّ كلّه، متحاذيًا) ⇐ تجريد
 * أداة التعريف إلى الثبات ⇐ تقنين الأرقام. الترتيب هو ما يحفظ «آلي» ويوحّد
 * «الإلزامية»/«إلزامية». `null` ⇐ `[]`.
 */
export function tokenize(text: string | null | undefined): string[] {
  const light = normalizeArLight(text);
  const lightRuns = light.match(TOKEN_RUN) ?? [];
  let strictRuns: string[] = normalizeArStrict(light).match(TOKEN_RUN) ?? [];
  // احتياط لا يُتوقَّع بلوغه: لو اختلّت المحاذاة يُطوى كل مقطع على حدة.
  if (strictRuns.length !== lightRuns.length)
    strictRuns = lightRuns.map((t) => normalizeArStrict(t));
  const out: string[] = [];
  for (let i = 0; i < lightRuns.length; i++) {
    const l = lightRuns[i];
    if (!longEnough(l) || ARABIC_STOPWORDS.has(l)) continue;
    for (const c of articleCandidates(strictRuns[i])) {
      const t = canonicalToken(c);
      if (longEnough(t)) out.push(t);
    }
  }
  return out;
}

export interface Bm25Doc {
  id: string;
  /** نصّ الوثيقة؛ `null` يُفهرس فارغًا (صفوف القاعدة ذات الأعمدة القابلة للفراغ في الخطوة ٢). */
  text: string | null;
}

export interface Bm25Options {
  k1?: number;
  b?: number;
  maxDocs?: number;
  maxDocChars?: number;
}

export interface Bm25Stats {
  /** وثائق دخلت الفهرس. */
  indexed: number;
  /** وثائق أُسقطت لتجاوز `maxDocs` — تُبلَّغ لا تُخفى. */
  dropped: number;
  /** وثائق قُصّ نصّها عند `maxDocChars`. */
  truncated: number;
  /** وثائق بلا مقطع واحد (نصّ فارغ أو `null` أو كلمات وصل فقط). */
  empty: number;
}

export interface Bm25Index {
  readonly k1: number;
  readonly b: number;
  /** طول كل وثيقة بالمقاطع، بترتيب الإدخال. */
  readonly docLengths: ReadonlyMap<string, number>;
  /** مقطع ⇐ (وثيقة ⇐ تردد). */
  readonly postings: ReadonlyMap<string, ReadonlyMap<string, number>>;
  readonly avgDocLength: number;
  readonly stats: Bm25Stats;
}

/** حدّ BM25 لمقطع واحد — معرّض للاختبار المباشر (الحالة المزروعة لإشارة k1). */
export function bm25TermScore(
  tf: number,
  df: number,
  n: number,
  docLength: number,
  avgDocLength: number,
  k1: number,
  b: number,
): number {
  const idf = Math.log(1 + (n - df + 0.5) / (df + 0.5));
  const norm = 1 - b + (b * docLength) / (avgDocLength || 1);
  return (idf * (tf * (k1 + 1))) / (tf + k1 * norm);
}

export function buildBm25Index(docs: readonly Bm25Doc[], opts: Bm25Options = {}): Bm25Index {
  const k1 = opts.k1 ?? BM25_K1;
  const b = opts.b ?? BM25_B;
  const maxDocs = opts.maxDocs ?? BM25_MAX_DOCS;
  const maxDocChars = opts.maxDocChars ?? BM25_MAX_DOC_CHARS;
  if (!Number.isFinite(k1) || k1 <= 0) throw new RangeError(`BM25 k1 يجب أن يكون موجبًا: ${k1}`);
  if (!Number.isFinite(b) || b < 0 || b > 1)
    throw new RangeError(`BM25 b يجب أن يكون في [0,1]: ${b}`);
  if (!Number.isInteger(maxDocs) || maxDocs < 1)
    throw new RangeError(`maxDocs غير صالح: ${maxDocs}`);
  // سالبٌ يقصّ ذيل كل وثيقة بصمت (`slice(0, -3)`) ويبلّغ «قُصّ» كأن الذيل هو المقصوص؛ وكسرٌ يفهرس بقايا حرفين.
  if (!Number.isInteger(maxDocChars) || maxDocChars < 1)
    throw new RangeError(`maxDocChars غير صالح: ${maxDocChars}`);

  const docLengths = new Map<string, number>();
  const postings = new Map<string, Map<string, number>>();
  const stats: Bm25Stats = { indexed: 0, dropped: 0, truncated: 0, empty: 0 };
  const seen = new Set<string>();
  let totalLength = 0;

  for (const doc of docs) {
    // التكرار عيبٌ في المدخل يُرفض دائمًا — ولو جاء بعد السقف.
    if (seen.has(doc.id)) throw new RangeError(`معرّف وثيقة مكرّر في الفهرس: ${doc.id}`);
    seen.add(doc.id);
    if (docLengths.size >= maxDocs) {
      stats.dropped += 1;
      continue;
    }
    let text = doc.text ?? "";
    if (text.length > maxDocChars) {
      text = text.slice(0, maxDocChars);
      stats.truncated += 1;
    }
    const tokens = tokenize(text);
    docLengths.set(doc.id, tokens.length);
    totalLength += tokens.length;
    stats.indexed += 1;
    if (tokens.length === 0) stats.empty += 1;
    for (const t of tokens) {
      let bucket = postings.get(t);
      if (!bucket) {
        bucket = new Map();
        postings.set(t, bucket);
      }
      bucket.set(doc.id, (bucket.get(doc.id) ?? 0) + 1);
    }
  }
  return {
    k1,
    b,
    docLengths,
    postings,
    avgDocLength: docLengths.size ? totalLength / docLengths.size : 0,
    stats,
  };
}

export interface Bm25Hit {
  id: string;
  score: number;
  /** مقاطع الاستعلام التي وُجدت في الوثيقة — للتفسير لا للترتيب. */
  matched: string[];
}

/** حدّ النتائج صحيحٌ غير سالب وإلا `RangeError` — تشاركه الذراع التي تقصّ بنفسها. */
export function assertSearchLimit(limit: number): void {
  if (!Number.isInteger(limit) || limit < 0)
    throw new RangeError(`limit يجب أن يكون صحيحًا غير سالب: ${limit}`);
}

/**
 * استعلام فارغ أو من كلمات وصل فقط ⇐ `[]` بلا رمي. الاستعلام مقصوصٌ عند
 * `QUERY_MAX_CHARS` قبل التقطيع — فلا يحمل المستدعي عبء السقف. أمّا `limit`
 * فيُرفض ما ليس صحيحًا غير سالب كما يرفض الباني سقفَيه: `NaN` (مثل
 * `Number(undefined)` من معامل استعلام) كان يُفرغ الذراع بصمت عبر
 * `slice(0, NaN)`، و`2.5` كان يُقصّ إلى 2 بلا إعلان (قاسه المراجع ٢٠٢٦/١٠/٢٩).
 */
export function searchBm25(index: Bm25Index, query: string, limit = 10): Bm25Hit[] {
  assertSearchLimit(limit);
  const terms = Array.from(new Set(tokenize(query.slice(0, QUERY_MAX_CHARS))));
  if (terms.length === 0 || index.docLengths.size === 0) return [];
  const n = index.docLengths.size;
  const scores = new Map<string, { score: number; matched: string[] }>();
  for (const t of terms) {
    const bucket = index.postings.get(t);
    if (!bucket) continue;
    for (const [docId, tf] of bucket) {
      const dl = index.docLengths.get(docId) ?? 0;
      const s = bm25TermScore(tf, bucket.size, n, dl, index.avgDocLength, index.k1, index.b);
      const acc = scores.get(docId) ?? { score: 0, matched: [] };
      acc.score += s;
      acc.matched.push(t);
      scores.set(docId, acc);
    }
  }
  return Array.from(scores, ([id, v]) => ({ id, score: v.score, matched: v.matched }))
    .sort((a, b) => b.score - a.score || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .slice(0, limit);
}
