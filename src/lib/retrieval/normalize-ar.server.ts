/**
 * التطبيع العربي — ثلاثة مطبِّعات لثلاثة أغراض صريحة، لا نسخة رابعة متباينة.
 *
 * التدقيق (`docs/audit/SADEED_RAG_AUDIT_2026-10-29.md` §٢.٣) وجد ثلاث نسخ
 * متباينة من التطبيع في الريبو. هنا:
 *
 * ١. `normalizeArSqlParity` — مرآة **حرفية** لدالّة `normalize_ar` **كما في ملف
 *    الترحيل** (`supabase/migrations/20260727212435_*.sql`) لأي ذراع تقارن نصًّا
 *    في TypeScript بعمود طبّعته القاعدة. وتحمل عيوبها عمدًا، فالمرآة لا تُصلح:
 *    - `translate()` فيها ستّة عشر حرفًا مصدرًا وخمسة عشر هدفًا، فالحرف
 *      الثاني عشر (U+FE94، تاء مربوطة بشكلها النهائي) يقع على `ي` لا
 *      `ه`، والسادس عشر (U+0640، التطويل) يُحذف — وهذا سلوك Postgres الموثّق:
 *      «If from is longer than to, occurrences of the extra characters in
 *      from are deleted».
 *    - لا تطوي ؤ/ئ، ولا تحوّل الأرقام الهندية، ولا تعرف ی/ک الفارسيتين.
 *    التكافؤ مع **نصّ ملف الترحيل** يُثبته الاختبار بمحاكاة `translate` من
 *    الملف نفسه. أمّا التطابق مع الدالّة المثبَّتة فعلًا في قاعدة الإنتاج
 *    فذلك **لم يُقَس** (`supabase/migrations/**` ليست مصدر الحقيقة لمخطّط
 *    الإنتاج — قاعدة مصدر الحقيقة المكتسَبة في `CLAUDE.md`)؛ قياسه قراءةُ نصّ
 *    `pg_get_functiondef('public.normalize_ar'::regproc)` بعد إيقاظ الخلفية.
 *
 * ٢. `normalizeArLight` — طيٌّ خفيف **بلا طيّ حروف**: NFKC، حالة صغيرة، حذف
 *    الأحرف غير المرئية والعلامات، مسافات. تستعمله `bm25.server.ts`
 *    لمطابقة كلمات الوصل **قبل** طيّ الهمزة والألف المقصورة، لأن الطيّ الكامل
 *    يُسقط «آلي» على «إلى» («الي» في الحالين) فتضيع كلمةٌ حقيقية.
 *
 * ٣. `normalizeArStrict` — طيّ أغنى للفهرس الذاكري حيث يُطبَّع الطرفان
 *    (الاستعلام والمتن) بالدالّة نفسها فلا يلزم تكافؤ مع القاعدة.
 *
 * ## قرار ؤ/ئ في الصارم — وحدُّه
 *
 * `ؤ→و` و`ئ→ي` — الخيار نفسه في `normalizeText` القائمة
 * (`src/lib/sadeed/projects-maintenance-recall.server.ts:77-86`) وفي
 * `nx_ar_normalize` غير المطبَّقة (`20260728093100`)، فالمستودع متّفق عليه
 * في غير دالّة القاعدة. البديل (`→ء`) لم يُختَر لأنه يفصل
 * «مسؤول» عن «مسوول» الشائعة في الكتابة السريعة.
 *
 * **الحدّ الناتج، ويُصرَّح به:** مقعدا الهمزة **لا يُوحَّدان** — الإملاءان
 * القياسيان للكلمة الواحدة يبقيان مقطعين مختلفين: «مسؤول» ⇐ «مسوول» و«مسئول»
 * ⇐ «مسيول» (و«مسءول» ثالث)، فسؤالٌ بأحدهما لا يصل وثيقةً بالآخر. الخيار نفسه
 * في `ArabicNormalizer` في Lucene (يترك ؤ/ئ)، فهو مقبول لا مُخفى؛ وتوحيدهما
 * (`→ء` مع إعادة التبرير) قرارٌ لاحق إن طُلب. الحالة الموثِّقة في الاختبار.
 *
 * ## `lower()` مقابل `toLowerCase()`
 *
 * متطابقان على ASCII والعربية (لا حالة لها). على حروفٍ لاتينية غير ASCII قد
 * يختلفان بحسب locale القاعدة (C.utf8) — التكافؤ المضمون هنا للعربية وASCII
 * وحدهما، وهو ما يحمله المتن.
 *
 * ## ترتيب الحالة الصغيرة: بعد NFKC وقبل حذف العلامات
 *
 * `toLowerCase()` قد يولّد علامةً مركّبة: «İ» (U+0130) ⇐ «i» + U+0307. لو
 * جاءت الحالة الصغيرة **بعد** حذف العلامات لبقيت العلامة في المخرج فيشقّ
 * المقطع («stanbul») ويفقد الصارم ثباته (مخرجه على مخرجه يختلف). فالحالة
 * الصغيرة تلي NFKC مباشرةً في الخفيف والصارم، وحذف العلامات بعدها.
 *
 * ## العلامات وغير المرئي بخاصّية يونيكود لا بقوائم يدوية
 *
 * القائمة اليدوية الأولى أغفلت علامات الملحق العربي A (U+08D3–U+08FF) وعلامة
 * الاتجاه العربية U+061C وواصل الكلمات U+2060 والشرطة اللينة U+00AD، فكانت
 * تشقّ الكلمة مقطعين. فالصارم والخفيف يحذفان `\p{M}` (كل علامة مركّبة) و
 * `\p{Cf}` (كل حرف تنسيق) بعد NFKC، والتطويل U+0640 (وهو `Lm` لا `Cf`)
 * بالاسم.
 *
 * ## لماذا الهروب `\uXXXX` لا الحرف نفسه
 *
 * نصف هذه الأحرف غير مرئي (تطويل، فواصل صفرية، علامات اتجاه) ونصفها الآخر
 * أشكال عرض تتشابه بصريًّا بحروفها الأساسية؛ وحرفٌ خفيّ في صنف regex يُقرأ
 * خطأً ويُحذف بتحريرٍ عابر. فكل صنف regex هنا مكتوب بنقاط الرموز، والحرف
 * المقصود في تعليقٍ بجانبه للقارئ؛ ولا تطويل كاشيدة في نثر هذا الملف. الحارس
 * في `normalize-ar.contract.test.ts` يقرأ بايتات هذا الملف كلّه وملفه ويحمرّ
 * على أي حرفٍ خفيّ خام.
 */

// ── مرآة SQL ──────────────────────────────────────────────────────────────
// الأحرف التسعة الأولى من `translate` ← ا: أ إ آ ٱ ٲ ٳ ﺃ ﺇ ﺁ
const SQL_TO_ALEF = /[\u0623\u0625\u0622\u0671\u0672\u0673\uFE83\uFE87\uFE81]/g;
// الحرفان العاشر والحادي عشر ← ه: ة ﺓ
const SQL_TO_HEH = /[\u0629\uFE93]/g;
// الثاني عشر (U+FE94 — عيب الطول) والثالث عشر حتى الخامس عشر ← ي: ﺔ ى ﯨ ﯩ
const SQL_TO_YEH = /[\uFE94\u0649\uFBE8\uFBE9]/g;
// `regexp_replace(…, '[\u064B-\u0652\u0670\u0640]', '', 'g')` — التشكيل، الألف
// الخنجرية، والتطويل (محذوف مرّتين: السادس عشر في translate ثم هنا؛ النتيجة واحدة).
const SQL_STRIP = /[\u064B-\u0652\u0670\u0640]/g;

/** مرآة `public.normalize_ar(text)` كما في ملف الترحيل — بعيوبها. `null` ⇐ `""` كما `COALESCE`. */
export function normalizeArSqlParity(input: string | null | undefined): string {
  return (input ?? "")
    .replace(SQL_TO_ALEF, "ا")
    .replace(SQL_TO_HEH, "ه")
    .replace(SQL_TO_YEH, "ي")
    .replace(SQL_STRIP, "")
    .toLowerCase();
}

// ── الطيّ الخفيف والصارم ──────────────────────────────────────────────────
// كل علامة مركّبة (Mn/Mc/Me): التشكيل، الألف الخنجرية، علامات المصحف،
// U+0610–U+061A، والملحق العربي A U+08D3–U+08FF.
const STRICT_MARKS = /\p{M}/gu;
// التطويل U+0640 (Lm — خارج Cf) وكل حرف تنسيق: الفواصل الصفرية، علامات الاتجاه
// (ومنها U+061C العربية)، واصل الكلمات U+2060، الشرطة اللينة U+00AD، BOM.
const STRICT_INVISIBLES = /\u0640|\p{Cf}/gu;
// الهمزات على الألف والمدّ والوصل وألفا الهمزة الفوقية/التحتية: آ أ إ ٱ ٲ ٳ
const STRICT_ALEF = /[\u0622\u0623\u0625\u0671\u0672\u0673]/g;
const STRICT_TEH_MARBUTA = /\u0629/g; // ة
const STRICT_YEH_LIKE = /[\u0649\u06CC]/g; // ى، ی الفارسية
const STRICT_KEHEH = /\u06A9/g; // ک الفارسية
const STRICT_WAW_HAMZA = /\u0624/g; // ؤ
const STRICT_YEH_HAMZA = /\u0626/g; // ئ
const DIGITS_ARABIC_INDIC = /[\u0660-\u0669]/g; // ٠–٩
const DIGITS_EXTENDED = /[\u06F0-\u06F9]/g; // ۰–۹

function asciiDigit(base: number): (d: string) => string {
  return (d) => String.fromCharCode(d.charCodeAt(0) - base + 0x30);
}

/**
 * الطيّ الخفيف: ما يسبق طيّ الحروف في الصارم حرفًا بحرف — NFKC، حالة صغيرة،
 * حذف غير المرئي والعلامات، مسافات. لا يمسّ الهمزة ولا الألف المقصورة
 * ولا التاء المربوطة ولا الأرقام، فتبقى «إلى» و«آلي» كلمتين.
 */
export function normalizeArLight(input: string | null | undefined): string {
  return (input ?? "")
    .normalize("NFKC")
    .toLowerCase()
    .replace(STRICT_INVISIBLES, "")
    .replace(STRICT_MARKS, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * الطيّ الصارم للفهرس الذاكري. الترتيب مقصود: NFKC أولًا يعيد أشكال العرض
 * (ﺃ ﺔ ﻻ …) والعرض الكامل إلى حروفها الأساسية، ثم الحالة الصغيرة (قد تولّد
 * علامة — ترويسة الملف)، ثم تُحذف غير المرئي والعلامات، ثم تُطوى الحروف، ثم
 * الأرقام، ثم المسافات. مثالي الثبات: تطبيقه على مخرج `normalizeArLight` أو على
 * مخرجه هو يعطي النتيجة نفسها (يحرسه الاختبار على العربية وعلى «İ»).
 */
export function normalizeArStrict(input: string | null | undefined): string {
  return (input ?? "")
    .normalize("NFKC")
    .toLowerCase()
    .replace(STRICT_INVISIBLES, "")
    .replace(STRICT_MARKS, "")
    .replace(STRICT_ALEF, "ا")
    .replace(STRICT_TEH_MARBUTA, "ه")
    .replace(STRICT_YEH_LIKE, "ي")
    .replace(STRICT_KEHEH, "ك")
    .replace(STRICT_WAW_HAMZA, "و")
    .replace(STRICT_YEH_HAMZA, "ي")
    .replace(DIGITS_ARABIC_INDIC, asciiDigit(0x0660))
    .replace(DIGITS_EXTENDED, asciiDigit(0x06f0))
    .replace(/\s+/g, " ")
    .trim();
}
