/**
 * سطر الحالة في المخاطبة الصوتية بعد فشل الدور — بلا وعدٍ كاذب (المراجعة ٢٠٢٦/١١/٠٣).
 *
 * كان السطر المكتوب والمعروض «تعذّر الاتصال بمحرك الذكاء الآن — أواصل الإصغاء وسأجيب
 * فور استقراره». لا شيء في الكود يجيب لاحقًا: بعد المهلة (التي لا تُعاد تلقائيًّا) أو
 * بعد استنفاد الإعادتين يسقط السؤال، ولا زرّ إعادة بلا يدين — فالوعد «سأجيب» لا يفيه
 * كود، ويخالف مبدأ المستودع في `ERROR_MASK_AR` («بلا وعدٍ لا يفي به كود»، المادة ٢٧).
 * والتوصيف «تعذّر الاتصال» خاطئ لمهلةٍ بعد ٥٥ ث.
 *
 * فحصٌ على نصّ الكود (التعليقات تقتبس العبارة القديمة فتُنزع): الوعد غائب، وتوجيه
 * المستخدم إلى ما يملكه فعلًا — تكرار سؤاله — حاضر. المسار الصوتي نفسه يحتاج ميكروفونًا
 * ومحرّك نطق، فلا يُصيَّر هنا؛ أمّا الدليل على أنّ الوعد لا يفيه كود فهو أنّ الأثر لا يستدعي
 * `regenerate` ولا `sendMessage` على المهلة (`SadeedCopilot.progress.test.tsx` ③).
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const SOURCE = readFileSync("src/components/sadeed-core/SadeedCopilot.tsx", "utf8");
const strip = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^[ \t]*\/\/.*$/gm, "");
const CODE = strip(SOURCE);

describe("سطر الحالة الصوتي بعد الفشل", () => {
  it("actually read the file", () => {
    expect(CODE).toContain("setConvNotice(");
    expect(CODE).toContain("convModeRef.current");
  });

  it("لا وعدَ بجوابٍ لاحق لا يفيه كود", () => {
    // «وسأجيبك بصوت …» في تحيّة تعذّر تشغيلها وعدٌ يفيه الكود (الكلام يُرسل دورًا عاديًّا)،
    // فالفحص على وعد الفشل بعينه: الإصغاء ثم «سأجيب» بلا آلية تعيد السؤال.
    expect(CODE).not.toMatch(/فور استقراره|أواصل الإصغاء[^"`]*سأجيب|عند استقرار/);
  });

  it("يوجّه المستخدم إلى تكرار سؤاله", () => {
    expect(CODE).toMatch(/setConvNotice\("[^"]*كرّر سؤالك[^"]*"\)/);
  });
});
