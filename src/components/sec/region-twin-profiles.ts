/**
 * أنواع البنى. كلٌّ يُرسم بوجهين ليقف في الفضاء بدل أن يبدو ملصقًا:
 * `block` مبنى · `tank` خزّان أسطواني · `stack` مدخنة (وقد تشتعل) ·
 * `pylon` برج نقل · `crane` رافعة ميناء · `dome` قبّة تخزين.
 */
export type StructureKind = "block" | "tank" | "stack" | "pylon" | "crane" | "dome";

export interface Structure {
  kind: StructureKind;
  /** حافّة اليسار على المحور الأفقي، بإحداثيات `viewBox`. */
  x: number;
  /** العرض الظاهر للوجه المضاء. */
  w: number;
  /** الارتفاع فوق خطّ الأفق. */
  h: number;
  /** عمق الوجه الجانبي المظلم — صفرٌ يعني صورةً ظلّية بلا مجسّم. */
  depth?: number;
  /** شعلة حيّة أعلى المدخنة (مصافي الشرقية والجنوبية). */
  flare?: boolean;
}

