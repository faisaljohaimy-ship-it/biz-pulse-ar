/** كل البنى في الطبقتين — تُستعمل لتثبيت مرابط الأصول الحيّة. */
export function allStructures(profile: TwinProfile): Structure[] {
  return [...profile.mid, ...profile.near];
}

/**
 * مرابط الأصول الحيّة: مواضع حتميّة مشتقّة من هندسة المشهد نفسه، لا
 * عشوائية. الحتميّة شرط لا تجميل — موضعٌ يتبدّل عند كل رسم يجعل الكاميرا
 * تقفز بين إطارين، ويستحيل معه الإشارة إلى «تلك الكاميرا» في عرضٍ حيّ.
 */
export function anchorPoints(profile: TwinProfile, count: number): { x: number; y: number }[] {
  const hosts = profile.near;
  if (hosts.length === 0 || count <= 0) return [];
  return Array.from({ length: count }, (_, i) => {
    const host = hosts[i % hosts.length];
    // لفّة ثانية تُزيح المربط داخل البنية نفسها بدل أن يركب سابقه.
    const lap = Math.floor(i / hosts.length);
    const across = ((lap * 0.37 + 0.22) % 0.72) + 0.14;
    return {
      x: Math.round(host.x + host.w * across),
      y: Math.round(HORIZON_Y - host.h - 10 - lap * 16),
    };
  });
}
