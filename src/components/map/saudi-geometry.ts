/**
 * هل يقع الإحداثي داخل المملكة؟ `null`/`NaN` ⇐ لا.
 *
 * اختبار الشعاع (ray casting): يُعدّ كم مرّة يقطع شعاعٌ أفقي من النقطة
 * أضلاعَ المضلّع — فردٌ = داخل. لا مكتبة ولا حساب مثلثات.
 */
export function isInsideSaudi(lat: number | null | undefined, lng: number | null | undefined) {
  if (typeof lat !== "number" || typeof lng !== "number") return false;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  let inside = false;
  for (let i = 0, j = SAUDI_POLYGON.length - 1; i < SAUDI_POLYGON.length; j = i++) {
    const [xi, yi] = SAUDI_POLYGON[i];
    const [xj, yj] = SAUDI_POLYGON[j];
    const crosses = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (crosses) inside = !inside;
  }
  return inside;
}

/**
 * إسقاط lat/lng إلى نسبة مئوية داخل إطار العرض التخطيطي.
 *
 * خطّي مقصود: الرسم تخطيطيّ لا مسقطٌ جغرافي، والنطاق ضيّق (١٦° من العرض)
 * فانحناء الأرض فيه لا يُرى. إسقاطٌ حقيقي هنا تعقيدٌ بلا فرق مرئي.
 */
export function projectToPercent(lat: number, lng: number): { left: number; top: number } {
  const left = ((lng - 34) / (56 - 34)) * 84 + 8;
  const top = (1 - (lat - 16) / (32 - 16)) * 78 + 8;
  return { left, top };
}

