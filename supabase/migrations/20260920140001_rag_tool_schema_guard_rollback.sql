-- ════════════════════════════════════════════════════════════════════════
-- تراجع P0-1 — يُعيد الأدوات إلى ما كانت عليه قبل الحارس
-- ════════════════════════════════════════════════════════════════════════
--
-- الحالة السابقة كانت `enabled = true` لكلتا الأداتين، **وهي الحالة
-- المعطوبة** التي سجّلها `20260801183309`. فالتراجع هنا يُعيد عطلًا
-- معروفًا عن قصد — وهذا ما يعنيه التراجع: استعادةُ ما كان، لا تحسينُه.
--
-- ولا يُستعمل إلا إن ثبت أن الحارس نفسه سبّب ضررًا. وإلا فالمسار الصحيح
-- أمامه لا خلفه: تطبيق ترحيلات `20260728*` المنشئة للجداول، فيرفع الحارس
-- التعطيل من تلقائه عند إعادة تشغيله.
-- ════════════════════════════════════════════════════════════════════════

do $$
begin
  if to_regclass('public.tool_registry') is null then
    return;
  end if;

  update public.tool_registry
     set enabled = true,
         metadata = metadata - 'disabled_reason' - 'missing_dependency' - 'guarded_by',
         updated_at = now()
   where id in ('rag.propose_candidate', 'rag.record_gap')
     and metadata->>'guarded_by' = '20260920140000_rag_tool_schema_guard';
end $$;
